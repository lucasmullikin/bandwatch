#!/usr/bin/env python3
"""Build profiles/event-track.json from the LIVE lane definitions.

Deliberately NOT generated by make_profiles.py: that generator has fallen
behind the live profiles (it knows nothing of acars/aprs/uat978/lora915/
pager_survey and reverts every tuned dwell), so running it would delete
working lanes. The live JSONs are the real source of truth, so the lanes are
lifted verbatim from them and only the dwell is changed.

Why a huge dwell: broker.py picks the next lane as lanes[(idx+1) % len(lanes)].
On a one-lane device that is the SAME lane, so the broker stops and restarts it
every `seconds`. A short dwell would bounce readsb -- and every restart drops
the aircraft table and reopens the dongle -- precisely during an approach.
"""
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PROF = os.path.join(ROOT, "profiles")
DWELL = 7200          # 2 h: longer than any hold, so the lane never cycles

LOW = "LOW BAND 118-174 MHz -- set dipole ~50cm, or fit a discone"
HIGH = "HIGH BAND 225-1090 MHz -- set dipole ~17cm, or fit a discone"


def live_lane(profile, lane_id):
    """Lift a lane verbatim from a live profile so tuning is never reverted."""
    d = json.load(open(os.path.join(PROF, profile + ".json")))
    for dev in d["devices"].values():
        for lane in dev["lanes"]:
            if lane["id"] == lane_id:
                return json.loads(json.dumps(lane))
    raise SystemExit("lane %s not found in %s" % (lane_id, profile))


adsb = live_lane("watch-day", "adsb")
tower = live_lane("watch-night", "air_tower_voice")
for lane in (adsb, tower):
    lane["seconds"] = DWELL
    lane["enabled"] = True

out = {
    "name": "event-track",
    "description": (
        "EVENT: track one aircraft. ADS-B pinned ALONE on the high-band radio "
        "with a 2h dwell so 1090 never rotates or restarts mid-approach; BOI "
        "tower voice on the low radio so the landing clearance is captured "
        "alongside the track. Everything else is deaf while this runs. Held "
        "via schedule.json override_until, so it expires on its own."),
    "devices": {
        # serial, not index: librtlsdr order is not stable across a replug and a
        # swapped index presents as bad reception, not an error.
        "0": {"label": LOW, "lanes": [tower], "serial": "00000001"},
        "1": {"label": HIGH, "lanes": [adsb], "serial": "00000002"},
    },
}

path = os.path.join(PROF, "event-track.json")
with open(path, "w") as fh:
    json.dump(out, fh, indent=2)
print("wrote", path)
for k, v in out["devices"].items():
    for lane in v["lanes"]:
        print("  dev%s serial=%s  %-18s %ds  cmd=%s"
              % (k, v["serial"], lane["id"], lane["seconds"], lane["cmd"][0].split("/")[-1]))
